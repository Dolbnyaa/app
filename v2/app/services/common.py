"""Общие мелкие помощники, переиспользуемые несколькими сервисами."""


def jsonb_lang(value: dict, lang: str) -> str:
    """Достаёт локализованную строку из jsonb-поля вида {"en": ..., "ru": ...},
    с фолбэком на английский, если запрошенного языка вдруг нет."""
    return value.get(lang, value.get("en"))
